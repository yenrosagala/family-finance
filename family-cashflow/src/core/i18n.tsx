const strings: Record<Lang, Record<string, string>> = { en, id };

type Vars = Record<string, string | number>;

export type I18nValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Vars) => string;
  locale: string;
};

const I18nContext = createContext<I18nValue>({
  lang: 'en',
  setLang: () => {},
  t: (key) => en[key] ?? key,
  locale: 'en-US',
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((v) => {
        if (v === 'id' || v === 'en') setLangState(v);
      })
      .catch(() => {});
  }, []);

  const setLang = async (next: Lang) => {
    setLangState(next);
    try {
      await AsyncStorage.setItem(STORAGE_KEY, next);
    } catch {}
  };

  const t = (key: string, vars?: Vars): string => {
    let s = strings[lang][key] ?? en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.split(`{{${k}}}`).join(String(v));
      }
    }
    return s;
  };

  const value: I18nValue = { lang, setLang, t, locale: LOCALE_TAG[lang] };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}